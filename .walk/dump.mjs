import { chromium } from "playwright";
import { createClient } from "@supabase/supabase-js";
import fs from "fs";
const env = fs.readFileSync(".env.local", "utf8");
const db = createClient(env.match(/NEXT_PUBLIC_SUPABASE_URL=(.+)/)[1].trim(), env.match(/SUPABASE_SERVICE_ROLE_KEY=(.+)/)[1].trim());
const BASE = "https://celta-connect.vercel.app";
const fol = JSON.parse(fs.readFileSync(".walk/picks.json","utf8")).find(p=>p.assignment_type==="Focus on Learner" && p.first_status==="approved");
const b = await chromium.launch();
const page = await (await b.newContext({ timezoneId:"Europe/Istanbul" })).newPage();
const { data: l } = await db.auth.admin.generateLink({ type:"magiclink", email: fol.who.email });
await page.goto(`${BASE}/auth/confirm?token_hash=${l.properties.hashed_token}&type=magiclink&next=%2Fportfolio%2F${fol.trainee_id}%2Fassignments%2F${fol.id}`, { waitUntil:"domcontentloaded" });
await page.waitForTimeout(6000);
const t = await page.evaluate(()=>document.body.innerText);
console.log("URL:", page.url());
console.log("contains 'Clear and well supported':", t.includes("Clear and well supported"));
console.log("contains 'YOUR TUTOR':", /YOUR TUTOR/i.test(t));
const i = t.indexOf("Learner Profile");
console.log("\n--- around the first section ---\n" + t.slice(i, i+500));
await b.close();
